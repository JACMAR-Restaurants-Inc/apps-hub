/** "2026-09-25" as the reader writes a date, in Toronto. */
export function formatDay(lang: Lang, at: Date): string {
  return new Intl.DateTimeFormat(lang === 'fr' ? 'fr-CA' : 'en-CA', {
    timeZone: 'America/Toronto',
    day: 'numeric',
    month: 'long',
    year: 'numeric',
  }).format(at);
}
